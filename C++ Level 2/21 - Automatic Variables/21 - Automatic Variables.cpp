#include <iostream>
using namespace std;



int main()
{
	// Automatic Variables
	// The compiler automatically chooses the variable type from the assigned value 

	auto a = 10;				// int type 
	auto b = 10.5;				// double type
	auto c = 15.5f;             // float type
	auto d = "Fawaz Alzahrani"; // string type

	cout << a << endl;
	cout << b << endl;
	cout << c << endl;
	cout << d << endl;
}