// Tip 1
// You can collapse or expand any function
// by clicking the arrow (→ / ↓) next to it


// Tip 2
// Right-click any function call and select "Go to Definition"
// to jump directly to the function definition


// Tip 3
// Right-click any function call and select "Go to Declaration"
// to jump directly to the function declaration (a function without a body)
// Function declarations were explained in a previous lesson


// Tip 4
// Right-click any function and select "View Call Hierarchy"
// to open the Call Hierarchy window
//
// Calls To:
// Shows where this function is called from
//
// Calls From:
// Shows which functions are called inside this function


// Tip 5
// Right-click any function and select "Find All References"
// to see every place where the function is used
// including its declaration, definition, and function calls


// Tip 6
// Right-click any function and select "Peek Definition"
// to quickly view the function definition
// without leaving your current location


// Tip 7
// Right-click any function and select "Rename"
// to safely rename the function
// Visual Studio automatically updates
// every declaration, definition, and function call