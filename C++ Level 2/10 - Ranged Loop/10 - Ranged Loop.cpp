#include <iostream>
using namespace std;


int main()
{

	int Array[] = { 1, 2, 3, 4, 5 };

	for (int Number : Array)
	{
		cout << Number << endl;
	}



	/*
	
		for ( rangeDeclaration : rangeExpression ) 

		Take each element from the rangeExpression and put it into the rangeDeclaration
		

		Example:
		for (int Number : Numbers)

		Take each number from Numbers and put it into the Number variable
	
	*/
}