#include <iostream>
using namespace std;



int main()
{


	cout << "Result : " << (12 & 25) << endl;

	// The result will be 8
	// Because we convert 12 and 25 from decimal to binary
	// then perform the Bitwise AND operation on them
	// 
	// For example :
	// 12 in binary = 00001100
	// 25 in binary = 00011001
	// Now let's perform the AND operation
	/*
	
			00001100
		  & 00011001
		  ----------
			00001000  This is the result which is equal to 8 in decimal
	
	
	*/
}